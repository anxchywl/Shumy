const CARDS = Object.entries(WORDS).flatMap(([category, entries]) =>
  entries.map(([word, ...aliases]) => ({ word, category, answers: [word, ...aliases].map(normalize) })));

function normalize(text) {
  return text.toLowerCase().replaceAll('ё', 'е').replace(/[^\p{L}\p{N}]/gu, '');
}

function maskWord(word, hint) {
  let first = true;
  return word.replace(/\p{L}/gu, letter => {
    const show = first && hint;
    first = false;
    return show ? letter : '_';
  });
}

function validSegment(segment) {
  if (!Array.isArray(segment) || segment.length !== 6 || !segment.every(Number.isInteger)) return false;
  const [color, width, x1, y1, x2, y2] = segment;
  return color >= 0 && color < 7 && [5, 11, 23].includes(width) &&
    x1 >= 0 && x1 <= 960 && x2 >= 0 && x2 <= 960 &&
    y1 >= 0 && y1 <= 600 && y2 >= 0 && y2 <= 600;
}

